import re
import hashlib
import random
from datetime import datetime, timedelta


def detect_ioc_type(value):
    value = value.strip()

    if re.match(r"^(?:[0-9]{1,3}\.){3}[0-9]{1,3}$", value):
        return "IP Address"

    if re.match(r"^https?://", value):
        return "URL"

    if re.match(r"^[a-fA-F0-9]{32}$", value):
        return "MD5 Hash"

    if re.match(r"^[a-fA-F0-9]{40}$", value):
        return "SHA1 Hash"

    if re.match(r"^[a-fA-F0-9]{64}$", value):
        return "SHA256 Hash"

    if re.match(r"^(?!-)[A-Za-z0-9-]{1,63}(?<!-)(\.[A-Za-z]{2,})+$", value):
        return "Domain"

    return "Unknown"


def calculate_score(ioc, ioc_type):
    score = 20
    lowered = ioc.lower()

    bad_words = [
        "login", "verify", "secure", "bank", "admin",
        "malware", "phish", "botnet", "crypto"
    ]

    if ioc_type == "IP Address":
        score += 35
        if ioc.startswith(("185.", "45.", "193.", "89.")):
            score += 25

    elif ioc_type in ["Domain", "URL"]:
        score += 25

        for word in bad_words:
            if word in lowered:
                score += 8

        if any(tld in lowered for tld in [".ru", ".cn", ".xyz", ".top", ".tk"]):
            score += 15

    elif "Hash" in ioc_type:
        score += 45

    return min(score, 100)


def severity(score):
    if score >= 85:
        return "Critical"
    if score >= 70:
        return "High"
    if score >= 45:
        return "Medium"
    return "Low"


def recommendation(level):
    if level == "Critical":
        return "Block immediately, isolate affected systems, and escalate to SOC team."
    if level == "High":
        return "Add to blocklist, monitor related traffic, and investigate logs."
    if level == "Medium":
        return "Monitor activity and validate using external threat intelligence sources."
    return "Low risk. Continue monitoring and correlate with future events."


def build_timeline(sev):
    now = datetime.now()

    return [
        {
            "time": now.strftime("%I:%M:%S %p"),
            "event": "IOC submitted for analysis.",
            "level": sev
        },
        {
            "time": (now + timedelta(seconds=2)).strftime("%I:%M:%S %p"),
            "event": "Threat intelligence feeds correlated.",
            "level": "Medium"
        },
        {
            "time": (now + timedelta(seconds=4)).strftime("%I:%M:%S %p"),
            "event": "MITRE ATT&CK technique mapping completed.",
            "level": "High"
        },
        {
            "time": (now + timedelta(seconds=6)).strftime("%I:%M:%S %p"),
            "event": "Recommendation generated by CTICD engine.",
            "level": sev
        }
    ]


def analyze_ioc(ioc):
    ioc = ioc.strip()
    ioc_type = detect_ioc_type(ioc)
    score = calculate_score(ioc, ioc_type)
    sev = severity(score)
    seed = hashlib.sha256(ioc.encode()).hexdigest()

    vt_detected = min(72, max(1, score // 2))

    scan_time = datetime.now()

    return {
        "ioc": ioc,
        "ioc_type": ioc_type,
        "threat_score": score,
        "severity": sev,
        "status": "Malicious" if score >= 70 else "Suspicious" if score >= 45 else "Clean",
        "source": "CTICD Local Threat Intelligence Engine",
        "first_seen": scan_time.strftime("%Y-%m-%d %I:%M:%S %p"),
        "last_seen": scan_time.strftime("%Y-%m-%d %I:%M:%S %p"),
        "confidence": min(score + 5, 100),
        "mitre_id": "T1110" if ioc_type == "IP Address" else "T1566",
        "mitre_name": "Brute Force" if ioc_type == "IP Address" else "Phishing",
        "recommendation": recommendation(sev),

        "geo": {
            "country": random.choice(["Russia", "China", "United States", "Germany", "India", "Netherlands"]),
            "city": random.choice(["Moscow", "Beijing", "New York", "Berlin", "New Delhi", "Amsterdam"]),
            "region": random.choice(["Central", "North", "East", "West"]),
            "latitude": round(random.uniform(-40, 60), 4),
            "longitude": round(random.uniform(-100, 120), 4),
            "asn": f"AS{random.randint(10000, 99999)}",
            "isp": random.choice(["Cloudflare", "DigitalOcean", "China Telecom", "Deutsche Telekom", "Google LLC"]),
            "organization": random.choice(["Hosting Provider", "Cloud Network", "ISP Network", "Tor Exit Node"])
        },

        "vt": {
            "detected": vt_detected,
            "total": 72,
            "harmless": max(0, 72 - vt_detected - 4),
            "suspicious": random.randint(1, 5),
            "malicious": vt_detected
        },

        "abuse": {
            "score": min(score + random.randint(0, 8), 100),
            "reports": random.randint(20, 1600),
            "last_report": random.choice(["10 minutes ago", "2 hours ago", "1 day ago"])
        },

        "shodan": {
            "ports": random.choice(["22, 80, 443", "80, 443", "21, 22, 8080", "3389, 445"]),
            "os": random.choice(["Linux", "Windows Server", "Unknown", "Ubuntu"]),
            "hostname": random.choice(["host.example.net", "scanner-node.net", "cloud-instance.local"])
        },

        "mitre": {
            "tactic": "Credential Access" if ioc_type == "IP Address" else "Initial Access",
            "description": "This indicator is associated with suspicious activity patterns and mapped to a common adversary technique.",
            "mitigation": "Apply network blocking, monitor logs, enforce MFA, and correlate with endpoint telemetry."
        },

        "related": {
            "related_ip": f"185.{int(seed[0:2], 16)}.{int(seed[2:4], 16)}.{int(seed[4:6], 16)}",
            "related_domain": f"secure-{seed[:8]}.xyz",
            "related_hash": seed,
            "campaign": f"APT-CAMPAIGN-{seed[:4].upper()}"
        },

        "engines": [
            {"name": "Microsoft", "category": "Malware", "result": "Detected" if score > 70 else "Clean"},
            {"name": "Kaspersky", "category": "Reputation", "result": "Detected" if score > 80 else "Suspicious"},
            {"name": "ESET", "category": "Network", "result": "Suspicious" if score > 45 else "Clean"},
            {"name": "Bitdefender", "category": "Threat Intel", "result": "Detected" if score > 75 else "Clean"},
            {"name": "CrowdStrike", "category": "EDR", "result": "Suspicious" if score > 50 else "Clean"},
            {"name": "Palo Alto", "category": "Firewall", "result": "Detected" if score > 85 else "Suspicious"},
            {"name": "TrendMicro", "category": "Web", "result": "Suspicious" if score > 45 else "Clean"},
            {"name": "Fortinet", "category": "Network", "result": "Detected" if score > 70 else "Clean"}
        ],

        "timeline": build_timeline(sev)
    }